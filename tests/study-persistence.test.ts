import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
process.loadEnvFile('.env.local');
const {pool,withUserDatabase}=await import('../src/server/db.ts');
const {createStudyPlan,getStudyPlan,startStudyTask,studyPlanHistory}=await import('../src/features/study/repository.ts');
const {createCourse}=await import('../src/features/course/repository.ts');
const today=()=>new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Shanghai',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
test('study plans persist three lessons, isolate owners, keep versions and share time with custom courses',async t=>{
 const ids=[randomUUID(),randomUUID()];
 t.after(async()=>{await pool.query('DELETE FROM "user" WHERE id=ANY($1::text[])',[ids]);await pool.end();});
 for(const id of ids)await pool.query('INSERT INTO "user"(id,name,email,"emailVerified","createdAt","updatedAt") VALUES($1,$3,$2,true,now(),now())',[id,`${id}@example.test`,'Study fixture']);
 const created=await createStudyPlan(ids[0],'astronomy',today());
 assert.equal(created.payload.units.length,3);assert.equal(created.revision,0);
 assert.equal((await createStudyPlan(ids[0],'astronomy',today())).id,created.id);
 assert.equal(await getStudyPlan(ids[1],created.id),null);
 const cross=await withUserDatabase(ids[1],c=>c.query('SELECT id FROM study_plans WHERE id=$1',[created.id]));assert.equal(cross.rowCount,0);
 const first=created.payload.days.flatMap(d=>d.tasks).find(t=>t.kind==='learn'&&t.unitKey==='first:')!;
 const locked=created.payload.days.flatMap(d=>d.tasks).find(t=>t.kind==='learn'&&t.unitKey==='skill:life')!;
 await assert.rejects(startStudyTask(ids[0],created.id,locked.id,0),/前置/);
 const started=await startStudyTask(ids[0],created.id,first.id,0);assert.equal(started.href,'/lesson/astronomy');
 const saved=await getStudyPlan(ids[0],created.id);assert.ok(saved);assert.equal(saved.revision,1);
 await assert.rejects(startStudyTask(ids[1],created.id,first.id,0),/找不到/);
 const light=created.payload.days.flatMap(d=>d.tasks).find(t=>t.kind==='learn'&&t.unitKey==='skill:light')!;
 await assert.rejects(startStudyTask(ids[0],created.id,light.id,0),/版本/);
 await assert.rejects(createCourse(ids[0],randomUUID(),{topic:'天文学',days:'7',dailyMinutes:'30',startDate:today()}),/时间/);
 const versions=await studyPlanHistory(ids[0],created.id);assert.deepEqual(versions.map(r=>r.revision),[1,0]);assert.deepEqual(await studyPlanHistory(ids[1],created.id),[]);
 const reopened=await getStudyPlan(ids[0],created.id);assert.ok(reopened);assert.equal(reopened.payload.days.flatMap(d=>d.tasks).find(t=>t.id===first.id)?.state,'started');
});
