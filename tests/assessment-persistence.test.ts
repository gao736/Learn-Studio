import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {Pool} from 'pg';
import {astronomyPack} from '../src/features/assessment/catalog.ts';
import {fixtureMaterial} from './fixtures/course.ts';
process.loadEnvFile('.env.local');
const {pool,withUserDatabase}=await import('../src/server/db.ts');
const {startAssessment,submitAssessment,requestHelp,getAssessment,getProgress,requestReview,resolveReview,isReviewer,getStudy,createCandidate,publishPack,getPack}=await import('../src/features/assessment/repository.ts');
test('PostgreSQL assessment preserves independent evidence, access gates and reviewer decisions',async t=>{
  const ids=[randomUUID(),randomUUID(),randomUUID()];
  t.after(async()=>{await pool.query('DELETE FROM "user" WHERE id=ANY($1::text[])',[ids]);await pool.end();});
  for(const id of ids)await pool.query('INSERT INTO "user"(id,name,email,"emailVerified","createdAt","updatedAt") VALUES($1,$2,$3,true,now(),now())',[id,'M03规则验收',`${id}@example.test`]);
  const first=await startAssessment(ids[0],'astronomy','light','diagnosis');
  const simultaneous=await Promise.all([startAssessment(ids[0],'astronomy','light','diagnosis'),startAssessment(ids[0],'astronomy','light','skip')]);
  assert.ok(simultaneous.every(s=>s.id===first.id));
  assert.equal((await startAssessment(ids[0],'astronomy','light','exam')).id,first.id);
  const publicSession=await getAssessment(ids[0],first.id);
  assert.ok(!JSON.stringify(publicSession).includes('correctIndex'));
  assert.equal(await getAssessment(ids[1],first.id),null);
  assert.equal(await getStudy(ids[0],'astronomy','life'),null);
  await assert.rejects(startAssessment(ids[0],'astronomy','life','exam'),/前置/);
  await requestHelp(ids[0],first.id,'light-energy-1','answer');
  await requestHelp(ids[0],first.id,'light-energy-1','hint');
  assert.deepEqual((await getAssessment(ids[0],first.id))?.help['light-energy-1'].events.map((e:any)=>e.kind),['answer','hint']);
  const answers={'light-energy-1':'1','light-identity-1':'0','light-reflection-1':'2','light-satellite-1':'1','light-orbit-1':'0'};
  const stored=await submitAssessment(ids[0],first.id,answers);
  assert.equal(stored.feedback.filter((e:any)=>e.independent).length,4);
  assert.equal((await getProgress(ids[0],'astronomy')).light.passed,false);
  assert.deepEqual((await submitAssessment(ids[0],first.id,{})).feedback,stored.feedback);
  await assert.rejects(submitAssessment(ids[1],first.id,answers),/找不到/);
  const second=await startAssessment(ids[0],'astronomy','light','exam');
  const next=Object.fromEntries(Object.entries(answers).map(([k,v])=>[k.replace(/-1$/,'-2'),v]));
  await assert.rejects(submitAssessment(ids[0],second.id,{}),/完成/);
  assert.equal((await getAssessment(ids[0],second.id))?.state,'active');
  await submitAssessment(ids[0],second.id,next);
  assert.equal((await getProgress(ids[0],'astronomy')).light.passed,true);
  assert.deepEqual((await getProgress(ids[0],'astronomy')).light.weak,[]);
  assert.ok(await getStudy(ids[0],'astronomy','life'));
  const review=await requestReview(ids[0],second.id,'light-energy-2','这题需要核对评分依据');
  assert.equal((await requestReview(ids[0],second.id,'light-energy-2','重复点击应继续已有复核')).id,review.id);
  assert.equal((await getProgress(ids[0],'astronomy')).light.pending,true);
  assert.equal(await getStudy(ids[0],'astronomy','life'),null);
  await assert.rejects(resolveReview(ids[1],review.id,true,'按NASA材料确认'),/权限/);
  assert.equal(await isReviewer(ids[0]),false);
  await assert.rejects(withUserDatabase(ids[0],c=>c.query('INSERT INTO assessment_reviewers(user_id) VALUES($1)',[ids[0]])));
  const local=JSON.parse(await readFile('.runtime/local-db.json','utf8'));
  const admin=new Pool({host:'127.0.0.1',port:54329,database:'learning_platform',user:'learning_admin',password:local.adminPassword});
  t.after(()=>admin.end());
  await admin.query('INSERT INTO assessment_reviewers(user_id) VALUES($1)',[ids[2]]);
  await resolveReview(ids[2],review.id,true,'按来源与题意核对，答案符合评分依据。');
  assert.equal((await getProgress(ids[0],'astronomy')).light.passed,true);
  await resolveReview(ids[2],review.id,false,'重复决定不得覆盖首次记录。');
  assert.equal((await getProgress(ids[0],'astronomy')).light.passed,true);
  const life=await startAssessment(ids[0],'astronomy','life','skip');
  await submitAssessment(ids[0],life.id,{'life-birth-1':'1','life-gravity-1':'0','life-sequence-1':'2','life-lifetime-1':'0','life-remnant-1':'白矮星'});
  assert.equal((await getProgress(ids[0],'astronomy')).life.pending,true);
  const pending=(await withUserDatabase(ids[0],c=>c.query("SELECT id FROM assessment_reviews WHERE session_id=$1 AND question_id='life-remnant-1'",[life.id]))).rows[0];
  await resolveReview(ids[2],pending.id,true,'白矮星符合太阳这种质量恒星的结局。');
  assert.equal((await getProgress(ids[0],'astronomy')).life.passed,true);
  const hidden=await withUserDatabase(ids[1],c=>c.query('SELECT id FROM assessment_sessions WHERE id=$1',[life.id]));
  assert.equal(hidden.rowCount,0);
  const exhausted=await startAssessment(ids[0],'astronomy','light','exam');
  await submitAssessment(ids[0],exhausted.id,Object.fromEntries(Object.entries(answers).map(([k,v])=>[k.replace(/-1$/,'-3'),v])));
  await assert.rejects(startAssessment(ids[0],'astronomy','light','exam'),/新题/);
  const expired=await startAssessment(ids[2],'astronomy','light','diagnosis');
  await withUserDatabase(ids[2],c=>c.query("UPDATE assessment_sessions SET expires_at=now()-interval '1 minute' WHERE id=$1",[expired.id]));
  await assert.rejects(submitAssessment(ids[2],expired.id,answers),/过期/);
  assert.equal((await getAssessment(ids[2],expired.id))?.state,'expired');
  const renewed=await startAssessment(ids[2],'astronomy','light','skip');
  assert.notEqual(renewed.id,expired.id);
  await submitAssessment(ids[2],renewed.id,next);
  const self=await requestReview(ids[2],renewed.id,'light-energy-2','申请复核自己的结果以验证权限边界');
  await assert.rejects(resolveReview(ids[2],self.id,true,'自己给自己评分必须拒绝'),/自己/);

  // Private provider-shaped fixture solely to test the adapter, not evidence of a real model call.
  const course=randomUUID();
  await withUserDatabase(ids[1],c=>c.query("INSERT INTO learning_courses(id,owner_id,submission_key,goal,schedule,status,material,sources,provenance) VALUES($1,$2,$3,$4,'[]','ready',$5,$6,'simulation')",[course,ids[1],randomUUID(),JSON.stringify({topic:'验收课程'}),JSON.stringify(fixtureMaterial),JSON.stringify([{id:'s1',url:'https://science.nasa.gov/universe/stars/',title:'仅边界夹具'}])]));
  await assert.rejects(createCandidate(ids[1],course),/模拟/);
  await withUserDatabase(ids[1],c=>c.query("UPDATE learning_courses SET provenance='real' WHERE id=$1",[course]));
  const candidate=await createCandidate(ids[1],course);
  assert.equal(await createCandidate(ids[1],course),candidate);
  assert.equal(await getPack(ids[0],candidate),null);
  await assert.rejects(startAssessment(ids[1],candidate,'intro','exam'),/审核/);
  await assert.rejects(publishPack(ids[0],candidate,astronomyPack,'无授权不得批准课程'),/权限/);
  const practical=structuredClone(astronomyPack);practical.skills[0].requiresPractice=true;
  await publishPack(ids[2],candidate,practical,'按示例来源审核题族与补测题；实操必需。');
  const practicalSession=await startAssessment(ids[1],candidate,'light','skip');
  await submitAssessment(ids[1],practicalSession.id,{...answers,practicePassed:'true'});
  assert.equal((await getProgress(ids[1],candidate)).light.practiceMissing,true);
  assert.equal((await getProgress(ids[1],candidate)).light.passed,false);
});
