import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {Pool} from 'pg';
import {fixtureMaterial} from './fixtures/course.ts';
process.loadEnvFile('.env.local');
const {pool,withUserDatabase}=await import('../src/server/db.ts');
const {saveAttempt}=await import('../src/features/lesson/repository.ts');
const {saveCourseAttempt}=await import('../src/features/course/repository.ts');
const {startAssessment,submitAssessment,getProgress,requestReview}=await import('../src/features/assessment/repository.ts');
const {listReviews,startReview,getReview,submitReview,syncReviews}=await import('../src/features/review/repository.ts');
test('PostgreSQL reviews persist FSRS, isolate owners, reject early answers and apply each revision once',async t=>{
  const ids=[randomUUID(),randomUUID()];
  const local=JSON.parse(await readFile('.runtime/local-db.json','utf8'));
  const admin=new Pool({host:'127.0.0.1',port:54329,database:'learning_platform',user:'learning_admin',password:local.adminPassword});
  t.after(async()=>{await admin.query('GRANT UPDATE ON review_cards TO learning_app');await pool.query('DELETE FROM "user" WHERE id=ANY($1::text[])',[ids]);await admin.end();await pool.end();});
  for(const id of ids)await pool.query('INSERT INTO "user"(id,name,email,"emailVerified","createdAt","updatedAt") VALUES($1,$2,$3,true,now(),now())',[id,'M04规则验收',`${id}@example.test`]);
  const answers={q1:'1',q2:'0',q3:'2',q4:'1',q5:'0'};
  await saveAttempt(ids[0],randomUUID(),answers);
  const seeded=await listReviews(ids[0]);assert.equal(seeded.due.length,5);
  assert.equal((await listReviews(ids[1])).due.length,0);
  assert.equal((await syncReviews(ids[0])).added,0);
  const card=seeded.due[0];
  const first=await startReview(ids[0],card.id);
  const repeated=await Promise.all([startReview(ids[0],card.id),startReview(ids[0],card.id)]);
  assert.ok(repeated.every(a=>a===first));
  assert.ok(!JSON.stringify(await getReview(ids[0],first)).includes('correctIndex'));
  assert.equal(await getReview(ids[1],first),null);
  assert.equal((await withUserDatabase(ids[1],c=>c.query('SELECT id FROM review_cards WHERE id=$1',[card.id]))).rowCount,0);
  await assert.rejects(submitReview(ids[1],first,'0','easy'),/找不到/);
  await assert.rejects(submitReview(ids[0],first,'99','easy'),/复习/);
  const key=(await withUserDatabase(ids[0],c=>c.query('SELECT question FROM review_cards WHERE id=$1',[card.id]))).rows[0].question.correctIndex;
  await admin.query('REVOKE UPDATE ON review_cards FROM learning_app');
  await assert.rejects(submitReview(ids[0],first,String(key),'good'));
  assert.equal((await getReview(ids[0],first))?.state,'pending');
  await admin.query('GRANT UPDATE ON review_cards TO learning_app');
  const wrong=String((key+1)%3);
  const outcomes=await Promise.all([submitReview(ids[0],first,wrong,'easy'),submitReview(ids[0],first,wrong,'good')]);
  assert.ok(outcomes.every(a=>a.feedback.correct===false&&a.feedback.rating===1));
  const saved=await getReview(ids[0],first);assert.equal(saved?.feedback?.correct,false);
  const stored=(await withUserDatabase(ids[0],c=>c.query('SELECT * FROM review_cards WHERE id=$1',[card.id]))).rows[0];
  assert.equal(stored.revision,1);assert.equal(stored.memory.reps,1);assert.equal(stored.memory.due,new Date(stored.due).toISOString());
  assert.equal((await withUserDatabase(ids[0],c=>c.query("SELECT count(*)::int AS n FROM review_attempts WHERE card_id=$1 AND state='submitted'",[card.id]))).rows[0].n,1);
  assert.equal((await listReviews(ids[0])).due.length,4);
  await assert.rejects(startReview(ids[0],card.id),/尚未到期/);
  await withUserDatabase(ids[0],c=>c.query("UPDATE review_cards SET due=now()-interval '1 minute' WHERE id=$1",[card.id])); // fixture clock only, no app clock override
  const second=await startReview(ids[0],card.id);assert.notEqual(second,first);
  await submitReview(ids[0],second,String(key),'good');
  const next=(await withUserDatabase(ids[0],c=>c.query('SELECT revision,memory FROM review_cards WHERE id=$1',[card.id]))).rows[0];
  assert.equal(next.revision,2);assert.equal(next.memory.reps,2);
  assert.equal((await submitReview(ids[0],first,'0','easy')).feedback.correct,false);
  assert.equal((await listReviews(ids[0])).history.filter((a:any)=>a.card_id===card.id).length,2);
  const a=await startAssessment(ids[0],'astronomy','light','diagnosis');
  await submitAssessment(ids[0],a.id,{'light-energy-1':'1','light-identity-1':'0','light-reflection-1':'2','light-satellite-1':'1','light-orbit-1':'0'});
  const before=await getProgress(ids[0],'astronomy');
  const item=(await listReviews(ids[0])).due.find((c:any)=>c.session_id===a.id)!;assert.ok(item);
  const active=await startReview(ids[0],item.id);
  const itemKey=(await withUserDatabase(ids[0],c=>c.query('SELECT question FROM review_cards WHERE id=$1',[item.id]))).rows[0].question.correctIndex;
  await submitReview(ids[0],active,String(itemKey),'easy');assert.deepEqual(await getProgress(ids[0],'astronomy'),before);
  const questioned=(await listReviews(ids[0])).due.find((c:any)=>c.session_id===a.id)!;
  const paused=await startReview(ids[0],questioned.id);
  const questionId=(await withUserDatabase(ids[0],c=>c.query('SELECT question_id FROM review_cards WHERE id=$1',[questioned.id]))).rows[0].question_id;
  await requestReview(ids[0],a.id,questionId,'这题需要再次核对来源和评分');
  await assert.rejects(submitReview(ids[0],paused,'0','easy'),/复核/);
  assert.equal((await listReviews(ids[0])).paused,1);
  // Old records are synced without overwriting cards or resetting schedules.
  const old=await saveAttempt(ids[1],randomUUID(),answers);
  await withUserDatabase(ids[1],c=>c.query('DELETE FROM review_cards WHERE lesson_attempt_id=$1',[old.id]));
  assert.equal((await syncReviews(ids[1])).added,5);assert.equal((await syncReviews(ids[1])).added,0);
  assert.equal((await syncReviews(ids[0])).added,0);
  // Database fixtures validate adapters only; no real model result or billing is asserted.
  const courseId=randomUUID(),generation=randomUUID();
  const goal={topic:'天文学',goal:'理解入门概念',days:7,dailyMinutes:30,startDate:'2026-10-07',sourceUrls:['https://science.nasa.gov/universe/stars/']};
  const sources=[{id:'s1',title:'NASA Stars',url:goal.sourceUrls[0],fetchedAt:new Date().toISOString(),digest:'fixture'}];
  await withUserDatabase(ids[1],c=>c.query("INSERT INTO learning_courses(id,owner_id,submission_key,goal,schedule,status,material,sources,provenance,active_generation) VALUES($1,$2,$3,$4,'[]','ready',$5,$6,'real',$7)",[courseId,ids[1],randomUUID(),JSON.stringify(goal),JSON.stringify(fixtureMaterial),JSON.stringify(sources),generation]));
  const reused=randomUUID();await saveAttempt(ids[1],reused,answers);
  await assert.rejects(saveCourseAttempt(ids[1],courseId,reused,answers),/凭证/);
  const realKey=randomUUID(),real=await saveCourseAttempt(ids[1],courseId,realKey,answers);
  await assert.rejects(saveAttempt(ids[1],realKey,answers),/凭证/);
  const privateCards=(await withUserDatabase(ids[1],c=>c.query('SELECT id FROM review_cards WHERE course_id=$1',[courseId]))).rows;
  assert.equal(privateCards.length,5);
  assert.equal((await withUserDatabase(ids[0],c=>c.query('SELECT id FROM review_cards WHERE course_id=$1',[courseId]))).rowCount,0);
  await assert.rejects(saveCourseAttempt(ids[0],courseId,randomUUID(),answers),/无权/);
  const realReview=await startReview(ids[1],privateCards[0].id);await submitReview(ids[1],realReview,'0','easy');
  await withUserDatabase(ids[1],c=>c.query('DELETE FROM learning_courses WHERE id=$1',[courseId]));
  assert.equal(await getReview(ids[1],realReview),null);
  await withUserDatabase(ids[0],c=>c.query("INSERT INTO learning_courses(id,owner_id,submission_key,goal,schedule,status,material,sources,provenance,active_generation) VALUES($1,$2,$3,$4,'[]','ready',$5,$6,'simulation',$7)",[randomUUID(),ids[0],randomUUID(),JSON.stringify(goal),JSON.stringify(fixtureMaterial),JSON.stringify(sources),randomUUID()]));
  const simulation=(await withUserDatabase(ids[0],c=>c.query('SELECT id FROM learning_courses WHERE owner_id=$1',[ids[0]]))).rows[0].id;
  await saveCourseAttempt(ids[0],simulation,randomUUID(),answers);
  assert.equal((await withUserDatabase(ids[0],c=>c.query('SELECT id FROM review_cards WHERE course_id=$1',[simulation]))).rowCount,0);
  assert.ok((await syncReviews(ids[0])).skipped>0);
  assert.ok(real.id);
});
